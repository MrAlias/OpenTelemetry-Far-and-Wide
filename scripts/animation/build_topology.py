"""Derive the presentation topology from the checked-in demo and lay it out with Graphviz."""
from pathlib import Path
import ast, hashlib, json, os, shlex, subprocess
import yaml

ROOT=Path(__file__).resolve().parents[2]
manifest=ROOT/'demo/k8s/applications.yaml'
resources=list(yaml.safe_load_all(manifest.read_text()))
deployments={r['metadata']['name']:r for r in resources if r and r['kind']=='Deployment'}
flow=ast.parse((ROOT/'demo/scripts/check-flow.py').read_text())
graph=next(ast.literal_eval(n.value) for n in flow.body if isinstance(n,ast.Assign) and any(isinstance(t,ast.Name) and t.id=='GRAPH' for t in n.targets))
runtimes={'gateway':'Go','checkout':'Java','inventory':'Node.js',**{n:v[0] for n,v in graph.items()}}
nodes=[];edges=[]
for name,runtime in runtimes.items():
 container=deployments[name]['spec']['template']['spec']['containers'][0]
 env={v['name']:v.get('value') for v in container.get('env',[])}
 calls=env.get('DOWNSTREAM_SERVICES',env.get('COMMERCE_SERVICES','')).split(',')
 if name=='gateway':calls=['checkout']
 if name=='checkout':calls=['inventory']+calls
 if name=='inventory':calls=[]
 edges.extend([name,n] for n in calls if n)
 if name in graph:assert calls==graph[name][1] or calls==[''] and graph[name][1]==[]
 nodes.append({'id':name,'label':name,'runtime':runtime,'eligible':runtime!='Go'})
assert len(nodes)==18 and sum(n['eligible'] for n in nodes)==14
assert {n['id'] for n in nodes}|{'postgres','redis'}==set(deployments)
assert len(edges)==17
work=ROOT/'.artifacts/storyboard/topology';work.mkdir(parents=True,exist_ok=True)
dot=['digraph Demo {','graph [rankdir=LR, nodesep=0.22, ranksep=0.28, margin=0, ordering=out];','node [shape=box, style=rounded, fontname="Inter", fontsize=19, margin="0.10,0.08", width=1.3, height=0.68];']
for n in nodes:dot.append(json.dumps(n['id'])+' [label='+json.dumps(n['label']+'\\n'+n['runtime'])+'];')
for a,b in edges:dot.append(json.dumps(a)+' -> '+json.dumps(b)+';')
dot.append('}')
source='\n'.join(dot).replace('\\\\n','\\n');(work/'demo.dot').write_text(source+'\n')
layout=subprocess.check_output(['dot','-Tplain'],input=source,text=True,env={**os.environ,'TMPDIR':str(work)})
(work/'demo.plain').write_text(layout)
parsed=[shlex.split(l) for l in layout.splitlines()]
_,_,gw,gh=parsed[0];gw=float(gw);gh=float(gh)
sx=1160/gw;sy=340/gh;ox=60;oy=200
xy=lambda x,y:[round(ox+float(x)*sx,3),round(oy+(gh-float(y))*sy,3)]
byid={n['id']:n for n in nodes};links=[]
for row in parsed:
 if row[0]=='node':
  _,name,x,y,w,h,*_=row;byid[name].update(x=xy(x,y)[0],y=xy(x,y)[1],w=round(float(w)*sx,3),h=round(float(h)*sy,3))
 if row[0]=='edge':
  count=int(row[3]);points=[xy(row[4+i*2],row[5+i*2]) for i in range(count)]
  links.append({'from':row[1],'to':row[2],'points':points})
model={'source':'demo/k8s/applications.yaml','manifestSha256':hashlib.sha256(manifest.read_bytes()).hexdigest(),'applications':18,'eligible':14,'nodes':nodes,'edges':links,'databases':{'PostgreSQL':['checkout','catalog','stock-planner','loyalty','receipts'],'Redis':['cart','recommendations','promotions']}}
(ROOT/'public/animation/topology-data.json').write_text(json.dumps(model,indent=2)+'\n')
(ROOT/'presentation/data').mkdir(parents=True,exist_ok=True)
(ROOT/'presentation/data/topology.json').write_text(json.dumps(model,indent=2)+'\n')
renderer=(ROOT/'scripts/animation/topology-renderer.js').read_text()
js='/* Generated by scripts/animation/build_topology.py from demo source. */\nwindow.DEMO_TOPOLOGY = '+json.dumps(model,separators=(',',':'))+';\n'+renderer
(ROOT/'public/animation/topology.js').write_text(js)
# The canonical storyboard remains self-contained and works offline.
p=ROOT/'public/storyboard.html';html=p.read_text();start='<!-- BEGIN DEMO TOPOLOGY -->';end='<!-- END DEMO TOPOLOGY -->'
block=start+'\n<script>\n'+js+'\n</script>\n'+end
if start in html:html=html[:html.index(start)]+block+html[html.index(end)+len(end):]
else:html=html.replace('<script>\n(()=>{',block+'\n<script>\n(()=>{',1)
p.write_text(html)
print('Derived 18 applications, 17 HTTP edges, 14 agent-eligible runtimes and 2 database dependency groups')
