assert.equal(data.controls.applicationServices,18)
assert.equal(data.controls.concurrency,1)
assert(data.before.requestMedianMs>data.after.requestMedianMs)
assert(data.before.pricingMedianMs>=2000&&data.after.pricingMedianMs<30)
assert(data.controls.sameImage)
assert.equal(data.controls.onlyChangedEnvironmentVariable,'LEGACY_PRICING_URL')
assert.equal(data.before.imageId,data.after.imageId)
assert.equal(data.before.image,data.after.image)
assert.match(data.controls.sameTemplateExceptLegacyUrlSha256,/^[a-f0-9]{64}$/)
